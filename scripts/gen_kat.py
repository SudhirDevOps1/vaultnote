"""Generate known-answer test vectors from independent implementations.

Why this exists
---------------
Vaultnote's Rust crypto tests are property-based: they check round-trips,
tamper detection and determinism. A property suite passes just as happily on a
subtly wrong implementation as on a correct one. What it cannot do is prove the
implementation agrees with anyone else.

So this script produces expected values from two *separate* implementations:

  - XChaCha20-Poly1305 : PyNaCl, which binds libsodium
  - Argon2id           : argon2-cffi, which binds the PHC-winner reference C
                         implementation

and emits them as a Rust test module. If RustCrypto's output matches, two
independent implementations agree.

The XChaCha20 inputs are copied verbatim from libsodium's own test suite
(test/default/aead_xchacha20poly1305.c), so these are not even
self-generated inputs.

Usage:
    python scripts/gen_kat.py          # writes src-tauri/tests/kat_vectors.rs
    python scripts/gen_kat.py -        # writes to stdout

The script writes the file itself rather than relying on shell redirection:
PowerShell's `>` emits UTF-16, which is not a valid Rust source encoding.
"""

import os
import sys

from argon2.low_level import Type, hash_secret_raw
from nacl.bindings import crypto_aead_xchacha20poly1305_ietf_encrypt

# ---------------------------------------------------------------------------
# XChaCha20-Poly1305 - inputs from libsodium's test suite, expected ciphertext
# from libsodium via PyNaCl.
# ---------------------------------------------------------------------------

LIBSODIUM_KEY = bytes(range(0x80, 0xA0))
LIBSODIUM_NONCE = bytes([
    0x07, 0x00, 0x00, 0x00, 0x40, 0x41, 0x42, 0x43,
    0x44, 0x45, 0x46, 0x47, 0x48, 0x49, 0x4A, 0x4B,
    0x4C, 0x4D, 0x4E, 0x4F, 0x50, 0x51, 0x52, 0x53,
])
LIBSODIUM_AD = bytes([
    0x50, 0x51, 0x52, 0x53, 0xC0, 0xC1, 0xC2, 0xC3,
    0xC4, 0xC5, 0xC6, 0xC7,
])
LIBSODIUM_MSG = (
    b"Ladies and Gentlemen of the class of '99: If I could offer you "
    b"only one tip for the future, sunscreen would be it."
)

# Must match crypto::SALT_LEN and crypto::KEY_LEN.
SALT_LEN = 16
KEY_LEN = 32


def xchacha_cases():
    cases = [
        ("libsodium_suite_114b", LIBSODIUM_KEY, LIBSODIUM_NONCE,
         LIBSODIUM_AD, LIBSODIUM_MSG),
        ("empty_message", LIBSODIUM_KEY, LIBSODIUM_NONCE, b"", b""),
        ("no_ad", LIBSODIUM_KEY, LIBSODIUM_NONCE, b"", LIBSODIUM_MSG),
    ]
    out = []
    for name, key, nonce, aad, msg in cases:
        blob = crypto_aead_xchacha20poly1305_ietf_encrypt(msg, aad, nonce, key)
        body, tag = blob[:-16], blob[-16:]
        out.append((name, key, nonce, aad, msg, body, tag))
    return out


# ---------------------------------------------------------------------------
# Argon2id - expected hashes from the reference implementation.
# ---------------------------------------------------------------------------

ARGON2_CASES = [
    # (label, password, salt, m_cost KiB, t_cost, p_cost, out_len)
    ("fast_8mib_t1", b"correct horse", bytes([7] * 16), 8 * 1024, 1, 1, 32),
    ("fast_8mib_t2", b"correct horse", bytes([7] * 16), 8 * 1024, 2, 1, 32),
    ("libargon2_style", b"password", b"somesalt16byte!!", 16 * 1024, 2, 1, 32),
    # The configuration the app actually ships with.
    ("default_64mib_t3", b"correct horse", bytes([7] * 16), 64 * 1024, 3, 1, 32),
    # Non-ASCII must behave identically to any other byte string.
    ("unicode", "🔐 नोट्स".encode("utf-8"), bytes([0xAB] * 16),
     8 * 1024, 1, 1, 32),
    ("empty_password", b"", bytes([0x01] * 16), 8 * 1024, 1, 1, 32),
]


def argon2_cases():
    out = []
    for label, pw, salt, m, t, p, out_len in ARGON2_CASES:
        # The emitted struct field is a fixed [u8; 16], so catch a short salt
        # here rather than as a compile error in the generated file.
        if len(salt) != SALT_LEN:
            raise SystemExit(
                f"vector {label!r}: salt is {len(salt)} bytes, "
                f"expected {SALT_LEN}. Argon2 accepts 8..=64, but the generated "
                f"Rust field is a fixed [u8; {SALT_LEN}]."
            )
        if out_len != 32:
            raise SystemExit(
                f"vector {label!r}: out_len is {out_len}, expected 32 "
                f"(crypto::KEY_LEN)."
            )
        h = hash_secret_raw(
            secret=pw, salt=salt, time_cost=t, memory_cost=m,
            parallelism=p, hash_len=out_len, type=Type.ID, version=19,
        )
        out.append((label, pw, salt, m, t, p, out_len, h))
    return out


def rs_bytes(b, indent=16):
    pad = " " * indent
    lines = []
    for i in range(0, len(b), 12):
        chunk = b[i:i + 12]
        lines.append(pad + "".join(f"0x{x:02x}, " for x in chunk))
    return "\n".join(lines).rstrip(", ")


def emit(w=print):
    w("// Known-answer test vectors. GENERATED by scripts/gen_kat.py")
    w("// Do not hand-edit.")
    w("//")
    w("// Expected values come from two implementations that share no code")
    w("// with RustCrypto: PyNaCl (libsodium) for XChaCha20-Poly1305, and")
    w("// argon2-cffi (the PHC reference C implementation) for Argon2id.")
    w("// The XChaCha20 inputs are libsodium's own test-suite vectors.")
    w("//")
    w("// Regenerate with: python scripts/gen_kat.py")
    w("")
    w("#![allow(clippy::unreadable_literal)]")
    w("")

    w("pub struct XChaChaKat {")
    w("    pub name: &'static str,")
    w("    pub key: [u8; 32],")
    w("    pub nonce: [u8; 24],")
    w("    pub aad: &'static [u8],")
    w("    pub msg: &'static [u8],")
    w("    pub ct: &'static [u8],")
    w("    pub tag: &'static [u8],")
    w("}")
    w("")
    w("pub const XCHACHA_KATS: &[XChaChaKat] = &[")
    for name, key, nonce, aad, msg, body, tag in xchacha_cases():
        w("    XChaChaKat {")
        w(f'        name: "{name}",')
        w(f"        key: [{rs_bytes(key, 12)}],")
        w(f"        nonce: [{rs_bytes(nonce, 12)}],")
        w(f"        aad: &[{rs_bytes(aad, 12)}],")
        w(f"        msg: &[{rs_bytes(msg, 12)}],")
        w(f"        ct: &[{rs_bytes(body, 12)}],")
        w(f"        tag: &[{rs_bytes(tag, 12)}],")
        w("    },")
    w("];")
    w("")

    w("pub struct Argon2Kat {")
    w("    pub label: &'static str,")
    w("    pub password: &'static [u8],")
    w("    pub salt: [u8; 16],")
    w("    pub m_cost: u32,")
    w("    pub t_cost: u32,")
    w("    pub p_cost: u32,")
    w("    pub out_len: usize,")
    w("    pub expected: &'static [u8],")
    w("}")
    w("")
    w("pub const ARGON2ID_KATS: &[Argon2Kat] = &[")
    for label, pw, salt, m, t, p, out_len, h in argon2_cases():
        printable = all(32 <= c < 127 and c not in (34, 92) for c in pw)
        pw_lit = f'b"{pw.decode()}"' if printable else (
            "&[" + ", ".join(str(x) for x in pw) + "]")
        w("    Argon2Kat {")
        w(f'        label: "{label}",')
        w(f"        password: {pw_lit},")
        w(f"        salt: [{rs_bytes(salt, 12)}],")
        w(f"        m_cost: {m},")
        w(f"        t_cost: {t},")
        w(f"        p_cost: {p},")
        w(f"        out_len: {out_len},")
        w(f"        expected: &[{rs_bytes(h, 12)}],")
        w("    },")
    w("];")


def main():
    args = sys.argv[1:]
    if args and args[0] in ("-h", "--help"):
        print(__doc__)
        return

    if args and args[0] == "-":
        emit()
        return

    dest = args[0] if args else "src-tauri/tests/vectors/kat.rs"
    # Explicit UTF-8, no BOM, LF endings: a valid Rust source file regardless
    # of what shell the script is invoked from. Also creates the directory,
    # and the file lives in a subdirectory so cargo does not treat it as its
    # own integration-test target.
    os.makedirs(os.path.dirname(dest) or ".", exist_ok=True)
    # Explicit UTF-8, no BOM, LF endings: a valid Rust source file regardless
    # of what shell the script is invoked from.
    with open(dest, "w", encoding="utf-8", newline="\n") as fh:
        # print() appends a newline; raw write() does not, so add it here or
        # the whole file collapses onto one line.
        emit(lambda line: fh.write(line + "\n"))
    print(f"wrote {dest}", file=sys.stderr)


if __name__ == "__main__":
    main()